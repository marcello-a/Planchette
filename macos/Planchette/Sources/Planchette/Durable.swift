import Foundation

/// Durable terminals: the agent runs inside a **tmux** session, so its process
/// tree belongs to tmux's server instead of to Planchette.
///
/// Why this exists: Planchette *is* the terminal. libghostty forks the shell in
/// our process and holds the PTY master, so when the app exits the slave side
/// gets SIGHUP and every agent under it dies — an update, a crash or a quit ends
/// every running turn, and restore can only replay `claude --resume`, never the
/// work that was in flight. libghostty cannot adopt an existing PTY (there is no
/// fd or pty field in `ghostty_surface_config_s`), so the fix is not to make the
/// PTY survive but to make the *agent* survive: put it behind a multiplexer that
/// outlives us and re-attach on the way back.
///
/// What it does and does not cover:
/// - covers app quit, Install & Relaunch, and an app crash,
/// - does **not** cover a reboot or a logout, which end tmux's server too.
enum Durable {
    /// Where tmux normally lives. Searched in order, absolutely: a GUI app's
    /// PATH does not include Homebrew, so `which tmux` is no use to us.
    static let candidatePaths = [
        "/opt/homebrew/bin/tmux",   // Apple silicon Homebrew
        "/usr/local/bin/tmux",      // Intel Homebrew, manual installs
        "/opt/local/bin/tmux",      // MacPorts
        "/usr/bin/tmux",            // a future system tmux
    ]

    /// Pure (with an injectable probe, so it is testable): the first tmux found.
    static func tmuxPath(
        searching candidates: [String] = candidatePaths,
        isExecutable: (String) -> Bool = { FileManager.default.isExecutableFile(atPath: $0) }
    ) -> String? {
        candidates.first(where: isExecutable)
    }

    static var isAvailable: Bool { tmuxPath() != nil }

    /// What Settings offers to copy or type when tmux is missing. Homebrew is
    /// the one package manager a Mac that lacks tmux plausibly has; MacPorts
    /// users know their own spelling.
    static let installCommand = "brew install tmux"

    /// Our own tmux server, separate from whatever the user runs themselves.
    ///
    /// Not hygiene — necessity. The options a durable terminal needs to behave
    /// like an ordinary one (`extended-keys`, `set-clipboard`, `escape-time`,
    /// `terminal-features`) are **server** options in tmux: there is no way to
    /// set them for one session only. On a shared server we would be silently
    /// reconfiguring the user's own tmux; on our own server we can ask for
    /// exactly the fidelity we need and touch nothing of theirs.
    /// An instance running against an overridden state directory gets its own
    /// server: it knows nothing about the sessions of the normal instance, so on
    /// a shared server it would treat them as orphans and reap them.
    static let serverName = SupportPaths.instanceSuffix.map { "planchette-\($0)" } ?? "planchette"

    static var configURL: URL {
        SupportPaths.dir.appendingPathComponent("tmux.conf")
    }

    /// Pure: the config our server starts with.
    ///
    /// The goal is that a durable terminal is indistinguishable from a plain one.
    /// Two groups of settings get there:
    ///
    /// - **Invisibility.** No status bar taking the bottom row, and no prefix
    ///   key: the default `C-b` is backward-char in every emacs-mode shell and
    ///   is bound by agent TUIs. `history-limit` is raised because tmux's 2000
    ///   lines would otherwise be the scrollback ceiling.
    /// - **Pass the keyboard and screen through.** `extended-keys on` with the
    ///   `csi-u` encoding is what makes modified keys survive at all — with it
    ///   off (tmux's default) **Shift+Enter arrives as a plain Enter**, so an
    ///   agent submits the prompt instead of inserting a newline. The
    ///   `terminal-features` line tells tmux what the outer terminal can really
    ///   do, since it otherwise assumes far less than ghostty offers: truecolor,
    ///   OSC 52 clipboard, focus reporting, cursor shape/colour, underline
    ///   styles, hyperlinks and synchronised output. `allow-passthrough` lets an
    ///   escape sequence tmux does not understand reach the terminal instead of
    ///   being swallowed.
    ///
    /// The user's own `~/.tmux.conf` is deliberately not loaded: this server is
    /// plumbing, and their customisations (a prefix, a status bar, a theme) would
    /// be exactly the visible behaviour we are trying not to introduce.
    static let configContents = """
        # Generated by Planchette for durable terminals — do not edit.
        # This is a private tmux server (-L \(serverName)); nothing here affects
        # tmux sessions you start yourself.

        # tmux must not show through.
        set -g status off
        set -g prefix None
        set -g history-limit 50000

        # Report the terminal as faithfully as tmux can.
        set -s extended-keys on
        set -s extended-keys-format csi-u
        set -as terminal-features "*:extkeys:RGB:clipboard:focus:cstyle:ccolour:usstyle:strikethrough:overline:hyperlinks:sync"
        set -s set-clipboard on
        set -s escape-time 0
        set -g allow-passthrough on
        set -g focus-events on

        # The mouse. Without `mouse on`, tmux never asks the terminal for mouse
        # events — ghostty then falls back to its alternate-screen behaviour and
        # converts every wheel tick into an arrow key (tmux always holds the
        # terminal in the alternate screen), so scrolling at a shell prompt
        # cycled command history instead of showing output: the pane's real
        # history lives inside tmux, where ghostty's own scrollback cannot
        # reach. With it, tmux's default wheel bindings do the right thing per
        # pane: scroll OUR history at a prompt, forward to a program that asked
        # for the mouse, arrow keys for a full-screen program that did not
        # (less, vim). Selections made by mouse land on the system clipboard
        # via set-clipboard (OSC 52) above.
        set -g mouse on
        # No tmux context menus — Planchette shows its own native menu instead
        # (the app never reports a right-click into a durable terminal).
        unbind -n MouseDown3Pane
        unbind -n M-MouseDown3Pane
        unbind -n MouseDown3Status
        unbind -n M-MouseDown3Status
        unbind -n MouseDown3StatusLeft
        unbind -n M-MouseDown3StatusLeft

        # Mouse selections behave like an ordinary terminal's. tmux's defaults
        # copy on release and then drop the selection, so it vanished under
        # the pointer and ⌘C found nothing to copy. Copy mode is only ever
        # entered by the mouse here (there is no prefix), so its keyboard
        # bindings go: the selection stays until the next click, and any key
        # leaves copy mode and still reaches the program (`Any` runs for every
        # key without its own binding; a bare send-keys resends that key).
        # The other mouse events are bound to a no-op so `Any` cannot see
        # them: a click into scrolled-back history must not jump to the end.
        set -g mode-keys emacs
        unbind -T copy-mode -a
        bind -T copy-mode WheelUpPane select-pane \\; send -X -N 5 scroll-up
        bind -T copy-mode WheelDownPane select-pane \\; send -X -N 5 scroll-down
        bind -T copy-mode MouseDown1Pane select-pane \\; send -X clear-selection
        bind -T copy-mode MouseDrag1Pane select-pane \\; send -X begin-selection
        bind -T copy-mode MouseDragEnd1Pane send -X copy-pipe-no-clear
        bind -T copy-mode DoubleClick1Pane select-pane \\; send -X select-word \\; send -X copy-pipe-no-clear
        bind -T copy-mode TripleClick1Pane select-pane \\; send -X select-line \\; send -X copy-pipe-no-clear
        \(mouseNoOps.map { "bind -T copy-mode \($0) select-pane" }.joined(separator: "\n"))
        bind -T copy-mode Any send -X cancel \\; send-keys
        bind -n DoubleClick1Pane select-pane -t = \\; if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" { send -M } { copy-mode -H ; send -X select-word ; send -X copy-pipe-no-clear }
        bind -n TripleClick1Pane select-pane -t = \\; if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" { send -M } { copy-mode -H ; send -X select-line ; send -X copy-pipe-no-clear }

        """

    /// Mouse events copy mode ignores, so its `Any` binding never treats them as typing.
    static let mouseNoOps: [String] = ["1", "2", "3"].flatMap { button in
        ["MouseUp", "SecondClick"].map { "\($0)\(button)Pane" }
    } + ["2", "3"].flatMap { button in
        ["MouseDown", "MouseDrag", "MouseDragEnd", "DoubleClick", "TripleClick"].map { "\($0)\(button)Pane" }
    }

    /// Write the config if it is missing or out of date, so an app update's
    /// settings apply the next time the server starts.
    static func writeConfigIfNeeded() {
        let url = configURL
        if let existing = try? String(contentsOf: url, encoding: .utf8),
           existing == configContents { return }
        try? FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try? configContents.write(to: url, atomically: true, encoding: .utf8)
    }

    // MARK: Where a command ends

    /// The directory a durable zsh starts with as its `ZDOTDIR` (see `shellMarksEnvironment`).
    static var zshDirectory: URL {
        SupportPaths.dir.appendingPathComponent("zsh", isDirectory: true)
    }

    /// Pure: the `.zshenv` a durable zsh reads first.
    ///
    /// A plain terminal learns that a command ended from Ghostty's shell integration: it
    /// writes OSC 133 `C` before a command and `D;<status>` after it, and Planchette turns
    /// that into the terminal's state (`AppState.commandFinished`). A durable terminal gets
    /// neither half. Ghostty loads its integration only into a shell it starts itself, and
    /// here tmux starts the shell; and tmux keeps OSC 133 for its own prompt marks rather
    /// than passing it on. So a Ctrl+C, a failed build or a dev server that stopped left the
    /// icon where it was.
    ///
    /// This file is the same trick Ghostty uses: zsh reads `$ZDOTDIR/.zshenv`, which puts
    /// the user's `ZDOTDIR` back at once (so nothing below this shell ever sees ours),
    /// sources their own `.zshenv`, and — in an interactive shell only — adds two hooks that
    /// write the marks wrapped for tmux's passthrough (`allow-passthrough` is on in our
    /// config). zsh hands every precmd hook the command's `$?`, so the order of the hooks does
    /// not matter. The user's `.zprofile` and `.zshrc` then load from their own `ZDOTDIR` as
    /// always.
    ///
    /// The precmd writes `C` again right before `D`: Ghostty reports a `D` only after a `C`
    /// that the same surface saw, and after a restart the new surface re-attaches to a command
    /// whose `C` went to the old one — a dev server or a Claude still running in tmux would then
    /// end unseen. The duration Ghostty measures is lost; Planchette reads only the status.
    ///
    /// Known limit, shared with Ghostty's own shim: a `ZDOTDIR` that `/etc/zshenv` sets only when
    /// none is set (`: ${ZDOTDIR:=…}`) is not applied, since ours is set at that point.
    static let zshenvContents = #"""
        # Generated by Planchette for durable terminals — do not edit.
        # Restores your ZDOTDIR, sources your .zshenv, then tells Planchette where each
        # command starts and ends (OSC 133, wrapped so that tmux passes it on).
        if [[ -n "${PLANCHETTE_ZSH_ZDOTDIR+X}" ]]; then
            'builtin' 'export' ZDOTDIR="$PLANCHETTE_ZSH_ZDOTDIR"
            'builtin' 'unset' 'PLANCHETTE_ZSH_ZDOTDIR'
        else
            'builtin' 'unset' 'ZDOTDIR'
        fi
        {
            'builtin' 'typeset' _planchette_file=${ZDOTDIR-$HOME}"/.zshenv"
            [[ ! -r "$_planchette_file" ]] || 'builtin' 'source' '--' "$_planchette_file"
        } always {
            'builtin' 'unset' '_planchette_file'
            if [[ -o 'interactive' ]]; then
                'builtin' 'typeset' -gi _planchette_cmd=0
                _planchette_preexec() {
                    _planchette_cmd=1
                    'builtin' 'print' -rn -- $'\ePtmux;\e\e]133;C\a\e\\'
                }
                _planchette_precmd() {
                    'builtin' 'local' -i _planchette_status=$?
                    (( _planchette_cmd )) || 'builtin' 'return' 0
                    _planchette_cmd=0
                    'builtin' 'print' -rn -- $'\ePtmux;\e\e]133;C\a\e\\'
                    'builtin' 'print' -rn -- $'\ePtmux;\e\e]133;D;'"$_planchette_status"$'\a\e\\'
                }
                'builtin' 'typeset' -ga precmd_functions preexec_functions
                precmd_functions=(_planchette_precmd ${precmd_functions:#_planchette_precmd})
                preexec_functions=(${preexec_functions:#_planchette_preexec} _planchette_preexec)
            fi
        }

        """#

    /// Write the shim if it is missing or out of date, like the tmux config. True when the file
    /// on disk is the shim: only then may a shell be pointed at it — a `ZDOTDIR` without its
    /// `.zshenv` would load none of the user's startup files at all.
    @discardableResult
    static func writeZshenvIfNeeded() -> Bool {
        let url = zshDirectory.appendingPathComponent(".zshenv")
        if let existing = try? String(contentsOf: url, encoding: .utf8),
           existing == zshenvContents { return true }
        try? FileManager.default.createDirectory(at: zshDirectory, withIntermediateDirectories: true)
        try? zshenvContents.write(to: url, atomically: true, encoding: .utf8)
        return (try? String(contentsOf: url, encoding: .utf8)) == zshenvContents
    }

    /// Pure: what a new durable session needs in its environment so that its shell reports
    /// where commands end (see `zshenvContents`). Only zsh has the hooks; for any other shell
    /// this is empty, and the terminal behaves as before. The user's own `ZDOTDIR`, if they
    /// have one, travels along so that the shim can put it back.
    static func shellMarksEnvironment(
        shell: String?, userZDOTDIR: String?, zshDirectory: String
    ) -> [(key: String, value: String)] {
        guard let shell, (shell as NSString).lastPathComponent == "zsh" else { return [] }
        var environment = [(key: "ZDOTDIR", value: zshDirectory)]
        if let userZDOTDIR { environment.append((key: "PLANCHETTE_ZSH_ZDOTDIR", value: userZDOTDIR)) }
        return environment
    }

    // MARK: When the shell ends

    /// Pure: whether a durable terminal whose tmux client just exited is over for good.
    ///
    /// libghostty turns on "wait after command" for every surface that runs a command, and a
    /// durable terminal runs `tmux` — so after `exit` the terminal kept showing "Process
    /// exited. Press any key to close the terminal." and stayed in the sidebar, in its old
    /// state, until a key was pressed. Only a session that really ended may close it, because
    /// the client also exits when the session lives on:
    /// - **`[exited]`** is what tmux prints when the session it showed was destroyed — its
    ///   shell ended, or it was killed;
    /// - `[detached …]` (another client took the session, as a restore does) and
    ///   `[lost server]` / `[server exited]` (tmux crashed or was killed — restore replays
    ///   those terminals) are not a closed shell, and the terminal stays.
    ///
    /// And tmux must have answered, without this session in its list: `nil` (no answer) is
    /// no licence to close anything.
    static func sessionEnded(
        _ id: UUID, screen: String?, listed: [(id: UUID, attached: Bool)]?
    ) -> Bool {
        guard let screen, let listed, !listed.contains(where: { $0.id == id }) else { return false }
        let lines = screen.components(separatedBy: "\n")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        // tmux's word is the last line it wrote, before anything Ghostty adds below it.
        guard let tmuxLine = lines.last(where: { $0.hasPrefix("[") && $0.hasSuffix("]") }) else { return false }
        return tmuxLine == "[exited]"
    }

    /// The tmux session name for a terminal. Derived from the persisted session
    /// id, which is what makes re-attach possible after a restart — the id is
    /// stable, so the name is too. Lowercased and dot-free: tmux treats `.` and
    /// `:` as window/pane separators in target names.
    static func sessionName(for id: UUID) -> String {
        "planchette-" + id.uuidString.lowercased()
    }

    /// Pure: the command a durable terminal runs instead of a plain shell.
    ///
    /// `-A` attaches to the session when it already exists and creates it
    /// otherwise — one command for both first launch and re-attach. `-D` detaches
    /// any other client, which is how the *stale* client left behind by a crashed
    /// Planchette gets evicted instead of fighting us for the terminal size.
    ///
    /// `-e` is not a convenience: a pane does **not** inherit the client's
    /// environment. One tmux server serves every session and keeps the
    /// environment of the client that happened to start it, so without `-e` the
    /// second durable terminal would run with the *first* one's
    /// `PLANCHETTE_SESSION` and report every hook event as that terminal.
    /// Values are only applied when the session is created; re-attaching leaves
    /// the existing session's environment alone, which is correct — its processes
    /// already hold those values, and the session id is stable across restarts.
    static func attachCommand(
        tmux: String,
        session: String,
        environment: [(key: String, value: String)] = []
    ) -> String {
        // -L: our own server (see `serverName`). -f: our config, which is what
        // makes the terminal behave like an ordinary one; it applies when this
        // command is the one that starts the server, and is ignored once it is
        // already running.
        var parts = [
            tmux, "-L", serverName, "-f", singleQuoted(configURL.path),
            "new-session", "-A", "-D", "-s", session,
        ]
        for (key, value) in environment {
            parts.append("-e")
            parts.append(singleQuoted("\(key)=\(value)"))
        }
        // Re-source the config on every attach. `-f` only applies when this
        // command is the one that starts the server — without this, a server
        // started by an older app version keeps the old settings until a
        // reboot, and a config fix (like `mouse on`) would never reach the
        // very users it is for. Sourcing twice is idempotent.
        parts.append("\\;")
        parts.append("source-file")
        parts.append(singleQuoted(configURL.path))
        return parts.joined(separator: " ")
    }

    /// Pure: POSIX single-quoting, so a value carrying quotes, `$` or `|` — the
    /// click command carries all three — survives the shell that runs this.
    static func singleQuoted(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    // MARK: Talking to tmux

    /// tmux answers in milliseconds, or its server is wedged. Either way the
    /// caller — a restore, a close, the orphan reaper — must not wait on it
    /// forever.
    private static let tmuxTimeout: TimeInterval = 10

    /// Run tmux and return its exit status (-1 when it could not be run or did
    /// not answer in time).
    @discardableResult
    private static func run(_ tmux: String, _ arguments: [String]) -> Int32 {
        guard let result = Subprocess.run(tmux, arguments, timeout: tmuxTimeout) else { return -1 }
        return result.status
    }

    private static func output(_ tmux: String, _ arguments: [String]) -> String? {
        guard let result = Subprocess.run(tmux, arguments, timeout: tmuxTimeout),
              !result.timedOut
        else { return nil }
        return result.stdoutString
    }

    /// End a session and everything in it. Called when a terminal or a whole
    /// project is closed on purpose — without this, durable sessions would pile
    /// up in tmux forever.
    static func killSession(for id: UUID) {
        guard let tmux = tmuxPath() else { return }
        run(tmux, ["-L", serverName, "kill-session", "-t", "=\(sessionName(for: id))"])
    }

    /// Everything the app needs to know about our sessions, in **one** call.
    /// Both questions asked of tmux — "is this terminal's agent still alive?"
    /// and "which sessions are orphans?" — are answered from this list, so a
    /// restore costs one subprocess rather than one per terminal.
    ///
    /// **nil means tmux did not answer** (it timed out, or could not be started) —
    /// which says nothing about which agents are alive, and must never be read as
    /// "none". An empty list is a real answer: tmux replied, there is no server, so
    /// no agent survived. The two used to be the same `[]`, which was harmless while
    /// the call could not time out; with a deadline, a slow tmux would have made a
    /// restore conclude that every live agent was dead and type a scrollback replay
    /// and `claude --resume` into the terminal of each one (see AGENTS.md).
    static func listSessions() -> [(id: UUID, attached: Bool)]? {
        guard let tmux = tmuxPath() else { return [] }   // no tmux at all: nothing lives in it
        guard let out = output(
            tmux,
            ["-L", serverName, "list-sessions", "-F", "#{session_name} #{session_attached}"])
        else { return nil }
        return parseSessionList(out)
    }

    /// Pure: which durable terminals a restore must treat as having a LIVE agent.
    /// When tmux did not answer, all of them: the cost of assuming wrongly is a
    /// terminal that comes back without its scrollback replay (the user resumes by
    /// hand); the cost of the opposite mistake is a second agent started next to
    /// the one that is running, and a snapshot written over its TUI.
    static func liveIDsForRestore(
        listed: [(id: UUID, attached: Bool)]?, durableIDs: Set<UUID>
    ) -> Set<UUID> {
        guard let listed else { return durableIDs }
        return liveIDs(in: listed)
    }

    /// Pure: every terminal tmux still holds a session for — i.e. whose agent
    /// survived and must be re-attached to rather than replayed into.
    static func liveIDs(in sessions: [(id: UUID, attached: Bool)]) -> Set<UUID> {
        Set(sessions.map(\.id))
    }

    /// What runs in front in each of our sessions' panes (`#{pane_current_command}`), by
    /// terminal. nil when tmux did not answer. A restart uses it to tell a surviving agent from
    /// a plain shell (`isShell`).
    static func paneCommands() -> [UUID: String]? {
        guard let tmux = tmuxPath() else { return [:] }
        guard let out = output(
            tmux, ["-L", serverName, "list-panes", "-a", "-F", "#{session_name} #{pane_current_command}"])
        else { return nil }
        return parsePaneCommands(out)
    }

    /// Pure: parse `list-panes -F '#{session_name} #{pane_current_command}'`, ours only.
    static func parsePaneCommands(_ output: String) -> [UUID: String] {
        var commands: [UUID: String] = [:]
        for line in output.components(separatedBy: "\n") {
            let fields = line.split(separator: " ", maxSplits: 1).map(String.init)
            guard fields.count == 2, fields[0].hasPrefix("planchette-"),
                  let id = UUID(uuidString: String(fields[0].dropFirst("planchette-".count)))
            else { continue }
            commands[id] = commands[id] ?? fields[1]
        }
        return commands
    }

    /// Pure: whether a pane's command is a shell at its prompt — nothing of an agent's runs.
    static func isShell(_ command: String) -> Bool {
        let name = command.hasPrefix("-") ? String(command.dropFirst()) : command
        return ["zsh", "bash", "sh", "fish", "dash", "ksh", "tcsh", "csh", "nu", "login"].contains(name)
    }

    /// One pane of our sessions: the shell's pid (`#{pane_pid}`) and what runs in front of it.
    struct Pane: Equatable {
        var pid: Int32
        var command: String
    }

    /// Every pane of our sessions, by terminal — `paneCommands` plus the shell's pid, which
    /// `childArguments` needs. nil when tmux did not answer.
    static func panes() -> [UUID: Pane]? {
        guard let tmux = tmuxPath() else { return [:] }
        guard let out = output(
            tmux, ["-L", serverName, "list-panes", "-a", "-F",
                   "#{session_name} #{pane_pid} #{pane_current_command}"])
        else { return nil }
        return parsePanes(out)
    }

    /// Pure: parse `list-panes -F '#{session_name} #{pane_pid} #{pane_current_command}'`, ours only.
    static func parsePanes(_ output: String) -> [UUID: Pane] {
        var panes: [UUID: Pane] = [:]
        for line in output.components(separatedBy: "\n") {
            let fields = line.split(separator: " ", maxSplits: 2).map(String.init)
            guard fields.count == 3, fields[0].hasPrefix("planchette-"),
                  let id = UUID(uuidString: String(fields[0].dropFirst("planchette-".count))),
                  let pid = Int32(fields[1])
            else { continue }
            panes[id] = panes[id] ?? Pane(pid: pid, command: fields[2])
        }
        return panes
    }

    /// The command lines of the processes the given shells started — what `kubectl` was told to
    /// do, which its name alone does not say. One `ps` for all of them; nil when it did not answer.
    static func childArguments(of parents: Set<Int32>) -> [Int32: String]? {
        guard !parents.isEmpty else { return [:] }
        guard let result = Subprocess.run("/bin/ps", ["-axo", "pid=,ppid=,args="], timeout: 5),
              !result.timedOut
        else { return nil }
        return parseChildArguments(result.stdoutString, parents: parents)
    }

    /// Pure: parse `ps -axo pid=,ppid=,args=` into the command lines of the children of
    /// `parents`, joined per parent (a pipeline is several children).
    static func parseChildArguments(_ output: String, parents: Set<Int32>) -> [Int32: String] {
        var children: [Int32: [String]] = [:]
        for line in output.components(separatedBy: "\n") {
            let fields = line.split(separator: " ", maxSplits: 2, omittingEmptySubsequences: true)
            guard fields.count == 3, let ppid = Int32(fields[1]), parents.contains(ppid) else { continue }
            children[ppid, default: []].append(String(fields[2]))
        }
        return children.mapValues { $0.joined(separator: " | ") }
    }

    /// Database clients and servers, by process name.
    static let databaseClients: Set<String> = [
        "psql", "pgcli", "postgres", "mysql", "mysqld", "mariadb", "mycli",
        "redis-cli", "redis-server", "iredis", "mongosh", "mongo", "mongod", "usql",
    ]

    /// Pure: whether the program in front is a database — a client or a server by its name, or a
    /// tunnel to one (`kubectl port-forward svc/postgres 5432:5432`, `ssh -L 3306:…`): a tunnel's
    /// name is only `kubectl`, so its command line decides, by a database word or a default port
    /// (Postgres 5432, MySQL 3306, Redis 6379, MongoDB 27017, Elasticsearch 9200).
    static func isDatabase(command: String, arguments: String?) -> Bool {
        if databaseClients.contains(command) { return true }
        if command.hasPrefix("cloud-sql-proxy") || command.hasPrefix("cloud_sql_proxy") { return true }
        guard let original = arguments else { return false }
        // `-L` is a tunnel and `-l` a login name: ssh's flags are read before anything is lowercased.
        let tunnel = (["kubectl", "oc"].contains(command) && original.contains("port-forward"))
            || (command == "ssh" && original.range(of: #"(^|\s)-\w*L"#, options: .regularExpression) != nil)
        guard tunnel else { return false }
        let arguments = original.lowercased()
        let word = #"postgres|mysql|mariadb|redis|mongo|elastic|database|\bdb\b"#
        let port = #"(^|[^0-9])(5432|3306|6379|27017|9200)([^0-9]|$)"#
        return arguments.range(of: word, options: .regularExpression) != nil
            || arguments.range(of: port, options: .regularExpression) != nil
    }

    /// Pure: the program a durable terminal runs in front of its shell, as a name worth
    /// showing — `k9s`, `kubectl`, `node`. Nil for a shell at its prompt, and for an agent: a live
    /// one speaks through its hooks, and an agent's process name is no name. The native Claude
    /// install runs a versioned file, so the kernel calls it `2.1.323`; a name that is only a
    /// version is taken to be an agent even before its first hook.
    static func foregroundProgram(paneCommand: String?, agentLive: Bool) -> String? {
        guard !agentLive, let command = paneCommand?.trimmingCharacters(in: .whitespaces),
              !command.isEmpty, !isShell(command)
        else { return nil }
        if ["claude", "codex"].contains(command) { return nil }
        if command.range(of: #"^\d+(\.\d+)+$"#, options: .regularExpression) != nil { return nil }
        return command
    }

    /// Pure: the sessions safe to reap.
    ///
    /// An attached session belongs to a Planchette that is running right now: a
    /// second instance starting fresh must not kill the first one's agents, and
    /// "is anyone attached" is the question that actually distinguishes the two.
    /// An orphan — the terminal was closed, or its app died — has no client,
    /// because the client dies with the app.
    static func unattachedIDs(in sessions: [(id: UUID, attached: Bool)]) -> Set<UUID> {
        Set(sessions.filter { !$0.attached }.map(\.id))
    }

    /// Nothing is reaped when tmux did not answer: an unknown session list is no
    /// licence to kill anything.
    static func unattachedSessionIDs() -> Set<UUID> {
        guard let listed = listSessions() else { return [] }
        return unattachedIDs(in: listed)
    }

    /// Pure: parse `tmux list-sessions -F '#{session_name} #{session_attached}'`.
    /// Anything that is not one of ours is ignored — the user's own tmux sessions
    /// are none of our business. A line without a readable attached count is
    /// reported as attached, so an unparsable session is never reaped.
    static func parseSessionList(_ output: String) -> [(id: UUID, attached: Bool)] {
        var sessions: [(id: UUID, attached: Bool)] = []
        for line in output.components(separatedBy: "\n") {
            let fields = line.trimmingCharacters(in: .whitespaces)
                .components(separatedBy: " ")
            guard let name = fields.first, name.hasPrefix("planchette-") else { continue }
            let raw = String(name.dropFirst("planchette-".count))
            guard let id = UUID(uuidString: raw) else { continue }
            let attached = fields.count > 1 ? fields[1] != "0" : true
            sessions.append((id, attached))
        }
        return sessions
    }
}

// MARK: Search

/// A durable terminal's history lives in tmux: the pane sits in the alternate screen,
/// so libghostty never sees a line that scrolled off it and cannot search them. The
/// find bar (⌘F) therefore drives tmux's own copy mode for a durable terminal — which
/// also highlights every match — and libghostty's search for a plain one.
///
/// Every command here is a pure argument list, so the quoting that matters (the
/// target, a needle that starts with `-` or ends with `;`) is tested; the runners
/// block for as long as tmux takes, with a deadline, and belong off the main thread.
extension Durable {
    /// What a pane command takes as its target for this terminal: the session, exactly
    /// (`=`), and its current window. The colon is not decoration: `=name` alone names
    /// a session, and a pane command asked for a pane answers "can't find pane".
    static func paneTarget(for id: UUID) -> String {
        "=\(sessionName(for: id)):"
    }

    /// The needle as tmux has to be given it. An argument that ends in `;` ends the
    /// command there; `\;` is the literal.
    static func escapedNeedle(_ needle: String) -> String {
        needle.hasSuffix(";") ? String(needle.dropLast()) + "\\;" : needle
    }

    /// Pure: one tmux invocation that searches the history from the newest line
    /// backward and prints `present:count`. The `--` keeps a needle that starts with
    /// `-` from being read as a flag; the needle is literal text, never a pattern.
    static func searchArguments(_ needle: String, session id: UUID) -> [String] {
        let target = paneTarget(for: id)
        return [
            "-L", serverName,
            "copy-mode", "-t", target, ";",
            "send-keys", "-X", "-t", target, "history-bottom", ";",
            "send-keys", "-X", "-t", target, "search-backward-text", "--", escapedNeedle(needle), ";",
            "display-message", "-p", "-t", target, "#{search_present}:#{search_count}",
        ]
    }

    /// Pure: on to the next match — the older one, the way the search started — or back
    /// to the previous, newer one.
    static func stepArguments(older: Bool, session id: UUID) -> [String] {
        ["-L", serverName, "send-keys", "-X", "-t", paneTarget(for: id),
         older ? "search-again" : "search-reverse"]
    }

    /// Pure: leave copy mode, which takes the highlights with it.
    static func endSearchArguments(session id: UUID) -> [String] {
        ["-L", serverName, "send-keys", "-X", "-t", paneTarget(for: id), "cancel"]
    }

    /// Pure: the number of matches out of `present:count`. `0:` is a real answer —
    /// nothing found — and anything that is not that shape is no answer at all.
    static func parseSearchReply(_ text: String) -> Int? {
        let parts = text.trimmingCharacters(in: .whitespacesAndNewlines)
            .split(separator: ":", omittingEmptySubsequences: false)
        guard parts.count == 2 else { return nil }
        if parts[0] == "0" { return 0 }
        guard parts[0] == "1", let count = Int(parts[1]) else { return nil }
        return count
    }

    /// Search the history of a durable terminal and highlight the matches: how many
    /// there are, or nil when tmux is not there or did not answer. Blocking.
    static func search(_ needle: String, in id: UUID) -> Int? {
        guard let tmux = tmuxPath(), !needle.isEmpty,
              let reply = output(tmux, searchArguments(needle, session: id))
        else { return nil }
        return parseSearchReply(reply)
    }

    /// Blocking.
    static func step(older: Bool, in id: UUID) {
        guard let tmux = tmuxPath() else { return }
        run(tmux, stepArguments(older: older, session: id))
    }

    /// Blocking. Harmless when the pane is not in copy mode.
    static func endSearch(in id: UUID) {
        guard let tmux = tmuxPath() else { return }
        run(tmux, endSearchArguments(session: id))
    }
}
